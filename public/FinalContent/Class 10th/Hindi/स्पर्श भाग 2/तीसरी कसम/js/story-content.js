// Show story part
function showStoryPart(partNumber) {
    console.log(`Showing story part: ${partNumber}`);
    
    // Update navigation buttons
    document.querySelectorAll('.story-nav-btn').forEach(btn => {
        btn.classList.remove('active');
        btn.setAttribute('aria-pressed', 'false');
    });
    
    // Find and activate the clicked button
    const clickedBtn = document.querySelector(`.story-nav-btn[onclick*="${partNumber}"]`);
    if (clickedBtn) {
        clickedBtn.classList.add('active');
        clickedBtn.setAttribute('aria-pressed', 'true');
    }
    
    // Load content
    const storyContent = document.getElementById('storyContent');
    if (storyContent && storyParts[partNumber]) {
        storyContent.innerHTML = storyParts[partNumber].content;
        currentStoryPart = partNumber;
        
        // Stop any ongoing narration
        if (window.narrator && window.narrator.currentUtterance) {
            window.narrator.stop();
        }
        
        // Reading indicators removed completely as requested
        
        // Highlight clearing removed as highlighting is disabled
        
        // Scroll to top of content
        storyContent.scrollTop = 0;
        
        // Automatically start narration for "तीसरी कसम के शिल्पकार शैलेंद्र" (part 2)
        if (partNumber === 2) {
            // Wait a moment for content to load, then start narration
            setTimeout(() => {
                if (window.narrator && window.narrator.enabled) {
                    console.log('Auto-starting narration for main story content');
                    readCurrentStoryPartAloud();
                } else {
                    console.log('Narrator not available for auto-start');
                }
            }, 800); // Give time for content to render
        }
        
        console.log(`Story part ${partNumber} loaded successfully`);
    } else {
        console.error(`Story part ${partNumber} not found or content element missing`);
    }
}

// Read current story part aloud
function readCurrentStoryPartAloud() {
    if (!window.narrator || !window.narrator.enabled) {
        console.log('Narrator not available or disabled');
        return;
    }
    
    const storyContent = document.getElementById('storyContent');
    if (!storyContent || !storyParts[currentStoryPart]) {
        console.error('No story content available to read');
        return;
    }
    
    // Stop any ongoing narration
    if (window.narrator.currentUtterance) {
        window.narrator.stop();
    }
    
    // Get all paragraphs from the current story part
    const paragraphs = storyContent.querySelectorAll('p, blockquote');
    if (paragraphs.length === 0) {
        console.log('No paragraphs found to read');
        return;
    }
    
    // Reading indicator removed completely as requested
    
    // Track timeouts for cleanup
    window.highlightTimeouts = window.highlightTimeouts || [];
    
    // Read paragraphs sequentially
    let currentParagraphIndex = 0;
    
    function readNextParagraph() {
        // Highlight clearing removed as highlighting is disabled
        
        if (currentParagraphIndex >= paragraphs.length) {
            // Reading complete
            return;
        }
        
        const paragraph = paragraphs[currentParagraphIndex];
        
        // Paragraph highlighting removed as requested
        
        // Scroll to the paragraph
        paragraph.scrollIntoView({ behavior: 'smooth', block: 'center' });
        
        // Get text content, excluding vocab tooltips
        let textToRead = paragraph.textContent;
        
        // Remove tooltip text that might be included
        const tooltips = paragraph.querySelectorAll('.vocab-tooltip');
        tooltips.forEach(tooltip => {
            textToRead = textToRead.replace(tooltip.textContent, '');
        });
        
        // Clean up the text
        textToRead = textToRead.replace(/\s+/g, ' ').trim();
        
        if (textToRead.length > 0) {
            // Set up callback for when this paragraph ends
            window.narrator.onEndCallback = function() {
                setTimeout(() => {
                    currentParagraphIndex++;
                    readNextParagraph();
                }, 500); // Small pause between paragraphs
            };
            
            // Read the paragraph
            window.narrator.speak(textToRead);
        } else {
            // Skip empty paragraphs
            currentParagraphIndex++;
            readNextParagraph();
        }
    }
    
    // Start reading
    readNextParagraph();
}

