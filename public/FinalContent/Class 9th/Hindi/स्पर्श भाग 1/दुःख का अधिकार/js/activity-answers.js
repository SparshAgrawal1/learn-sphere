// Check comprehension answers
function checkComprehensionAnswers(questionId, userAnswer) {
    const answer = activityAnswers.comprehension.oral[questionId] || 
                  activityAnswers.comprehension.written25_30[questionId] || 
                  activityAnswers.comprehension.written50_60[questionId] ||
                  activityAnswers.comprehension.ashay[questionId];
    
    if (!answer) return false;
    
    // Simple similarity check (can be enhanced)
    const similarity = calculateSimilarity(userAnswer.toLowerCase(), answer.toLowerCase());
    return similarity > 0.7; // 70% similarity threshold
}

// Calculate text similarity (simple implementation)
function calculateSimilarity(text1, text2) {
    const words1 = text1.split(/\s+/);
    const words2 = text2.split(/\s+/);
    
    let commonWords = 0;
    words1.forEach(word => {
        if (words2.includes(word)) {
            commonWords++;
        }
    });
    
    return commonWords / Math.max(words1.length, words2.length);
}

// Check language exercise answers
function checkLanguageAnswers(exerciseType, questionId, userAnswer) {
    const answers = activityAnswers.language[exerciseType];
    if (!answers || !answers[questionId]) return false;
    
    const correctAnswer = answers[questionId];
    return userAnswer.toLowerCase().trim() === correctAnswer.toLowerCase().trim();
}

// Check activity answers
function checkActivityAnswers(activityType, questionId, userAnswer) {
    const answers = activityAnswers.activities[activityType];
    if (!answers || !answers[questionId]) return false;
    
    const correctAnswer = answers[questionId];
    return userAnswer === correctAnswer;
}

// Get answer for a specific question
function getAnswer(questionId) {
    // Search in all answer categories
    for (const category in activityAnswers.comprehension) {
        if (activityAnswers.comprehension[category][questionId]) {
            return activityAnswers.comprehension[category][questionId];
        }
    }
    
    for (const category in activityAnswers.language) {
        if (activityAnswers.language[category][questionId]) {
            return activityAnswers.language[category][questionId];
        }
    }
    
    for (const category in activityAnswers.activities) {
        if (activityAnswers.activities[category][questionId]) {
            return activityAnswers.activities[category][questionId];
        }
    }
    
    return null;
}

// Show answer for a question
function showAnswer(questionId) {
    const answer = getAnswer(questionId);
    if (!answer) {
        console.log('Answer not found for question:', questionId);
        return;
    }
    
    const answerDiv = document.createElement('div');
    answerDiv.className = 'answer-display';
    answerDiv.innerHTML = `
        <div class="answer-content">
            <h4>उत्तर:</h4>
            <p>${answer}</p>
            <button class="close-answer-btn" onclick="this.parentNode.parentNode.remove()">बंद करें</button>
        </div>
    `;
    
    // Find the question element and append answer
    const questionElement = document.getElementById(questionId);
    if (questionElement) {
        questionElement.appendChild(answerDiv);
    }
}

// Initialize answer system
function initializeAnswerSystem() {
    console.log('Answer system initialized');
    
    // Add answer buttons to questions if needed
    addAnswerButtons();
}

// Add answer buttons to questions
function addAnswerButtons() {
    const questions = document.querySelectorAll('.question-item');
    questions.forEach(question => {
        const questionId = question.id;
        if (questionId && getAnswer(questionId)) {
            const answerBtn = document.createElement('button');
            answerBtn.className = 'show-answer-btn';
            answerBtn.textContent = 'उत्तर देखें';
            answerBtn.onclick = () => showAnswer(questionId);
            question.appendChild(answerBtn);
        }
    });
}

