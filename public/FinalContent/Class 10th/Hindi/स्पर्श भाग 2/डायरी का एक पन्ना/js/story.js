// Show specific story part
function showStoryPart(partNumber) {
    console.log(`Showing story part: ${partNumber}`);
    
    // Stop any ongoing narration when switching parts
    if (window.narrator && window.narrator.currentUtterance) {
        console.log('Stopping ongoing narration due to story part switch');
        window.narrator.stop();
        
        // Clear any reading indicators
        document.querySelectorAll('.reading-indicator').forEach(indicator => {
            indicator.classList.add('fade-out');
            setTimeout(() => {
                if (indicator.parentNode) indicator.remove();
            }, 500);
        });
        
        // Clear any paragraph highlights - REMOVED
        
        // Clear any timeouts
        if (window.readingTimeout && typeof clearTimeout === 'function') {
            clearTimeout(window.readingTimeout);
        }
        
        if (window.highlightTimeouts && typeof clearTimeout === 'function') {
            window.highlightTimeouts.forEach(timeout => clearTimeout(timeout));
            window.highlightTimeouts = [];
        }
    }
    
    const partIndex = partNumber - 1;
    if (partIndex < 0 || partIndex >= storyParts.length) {
        console.error(`Invalid story part number: ${partNumber}`);
        return;
    }
    
    const part = storyParts[partIndex];
    const storyContainer = document.getElementById('storyContent');
    
    if (!storyContainer) {
        console.error('Story container not found');
        return;
    }
    
    // Update the story content
    storyContainer.innerHTML = part.content;
    
    // Update the story title
    const storyTitle = document.getElementById('storyTitle');
    if (storyTitle) {
        storyTitle.textContent = part.title;
    }
    
    // Update navigation buttons
    updateStoryNavigation(partNumber);
    
    // Track completion
    if (!modulesCompleted.includes('story')) {
        modulesCompleted.push('story');
        updateProgress();
        showAchievement('कहानी पढ़ी गई!');
    }
    
    // Automatically start reading the new part
    setTimeout(() => {
        readStoryPartAloud(partNumber, false); // false = automatic call
    }, 200); // Small delay to ensure content is fully loaded
}

// Update story navigation buttons
function updateStoryNavigation(currentPart) {
    const prevBtn = document.getElementById('prevPartBtn');
    const nextBtn = document.getElementById('nextPartBtn');
    
    if (prevBtn) {
        prevBtn.disabled = currentPart <= 1;
        prevBtn.style.opacity = currentPart <= 1 ? '0.5' : '1';
    }
    
    if (nextBtn) {
        nextBtn.disabled = currentPart >= storyParts.length;
        nextBtn.style.opacity = currentPart >= storyParts.length ? '0.5' : '1';
    }
}

